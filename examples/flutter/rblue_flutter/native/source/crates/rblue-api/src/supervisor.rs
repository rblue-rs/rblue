    type EventSenders = Mutex<Vec<futures::channel::mpsc::UnboundedSender<AdapterEvent>>>;

    /// Best-effort broadcast hub for adapter events (test only).
    #[derive(Debug)]
    struct EventHub {
        subscribers: EventSenders,
    }

    impl EventHub {
        fn new() -> Arc<Self> {
            Arc::new(Self {
                subscribers: Mutex::new(Vec::new()),
            })
        }

        fn publish(&self, event: AdapterEvent) {
            let mut subscribers = self
                .subscribers
                .lock()
                .unwrap_or_else(|poisoned| poisoned.into_inner());
            subscribers.retain(|tx| tx.unbounded_send(event.clone()).is_ok());
        }

        fn subscribe(&self) -> futures::channel::mpsc::UnboundedReceiver<AdapterEvent> {
            let (tx, rx) = futures::channel::mpsc::unbounded();
            self.subscribers
                .lock()
                .unwrap_or_else(|poisoned| poisoned.into_inner())
                .push(tx);
            rx
        }
    }

