/// Timer duration used while no device is due; the loop still wakes on
/// real events, so this only bounds timer churn.
const IDLE_TICK: Duration = Duration::from_secs(3600);

/// Retry decision returned by the supervision state machine.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Disposition {
    /// The event was absorbed; nothing to schedule or surface.
    Ignored,
    /// Retry after waiting `delay`.
    RetryAfter(Duration),
    /// The circuit breaker opened; stop retrying until re-armed.
    BreakerOpen,
    /// [`ReconnectPolicy::max_attempts`] consecutive failures reached;
    /// stop retrying permanently until re-armed.
    GaveUp,
}

/// Phase of one supervised device.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SupervisionPhase {
    /// Registered and armed: the next loop tick starts an attempt.
    Armed,
    /// Link up, counters reset.
    Connected,
    /// A connect attempt is in flight.
    Attempting,
    /// Waiting out a backoff delay.
    Backoff,
    /// Circuit breaker open after too many consecutive failures.
    BreakerOpen,
    /// Gave up after `max_attempts` consecutive failures.
    GaveUp,
    /// Watched but not reconnecting (e.g. a deliberate local disconnect);
    /// `request` re-arms.
    Dormant,
}

/// Reconnection policy knobs. Defaults implement the plan policy: 500 ms
/// initial backoff, x2 growth, 30 s cap, +/-20% jitter, a longer base for
/// Android GATT status 133, and a circuit breaker at 5 consecutive
/// failures.
#[derive(Debug, Clone)]
pub struct ReconnectPolicy {
    /// Backoff before the first retry after a failure (500 ms by default).
    pub initial_backoff: Duration,
    /// Hard cap for the *base* backoff (30 s by default); jitter may push
    /// the effective delay up to `max_backoff * (1 + jitter_fraction)`.
    pub max_backoff: Duration,
    /// Growth factor per consecutive failure (2.0 by default). Values < 1
    /// are clamped to 1.
    pub multiplier: f64,
    /// Relative jitter applied to the base delay (0.2 = +/-20%). Values
    /// outside 0..=1 are clamped.
    pub jitter_fraction: f64,
    /// Base backoff used after an Android GATT status 133 failure
    /// (5 s by default); grows with the same multiplier and cap.
    pub gatt_133_backoff: Duration,
    /// Number of consecutive failures that opens the circuit breaker
    /// (5 by default); `None` disables the breaker.
    pub breaker_threshold: Option<u32>,
    /// Consecutive failures after which the supervisor gives up entirely
    /// (`None` = retry forever, the default). The breaker preempts this
    /// when both are configured.
    pub max_attempts: Option<u32>,
    /// Whether a `DisconnectReason::Local` event schedules a reconnect.
    /// `false` by default: a local disconnect is deliberate, and fighting
    /// the application would be wrong.
    pub reconnect_on_local_disconnect: bool,
    /// Seeds the jitter generator; `None` derives a stable seed from the
    /// device id. Set it for fully reproducible backoff sequences in tests.
    pub jitter_seed: Option<u64>,
}

impl Default for ReconnectPolicy {
    fn default() -> Self {
        Self {
            initial_backoff: Duration::from_millis(500),
            max_backoff: Duration::from_secs(30),
            multiplier: 2.0,
            jitter_fraction: 0.2,
            gatt_133_backoff: Duration::from_secs(5),
            breaker_threshold: Some(5),
            max_attempts: None,
            reconnect_on_local_disconnect: false,
            jitter_seed: None,
        }
    }
}

/// Returns `true` for the Android GATT "generic failure" connect status.
#[must_use]
pub fn is_android_gatt_133_reason(reason: Option<&DisconnectReason>) -> bool {
    matches!(reason, Some(DisconnectReason::Platform(133)))
}

/// Returns `true` when `error` carries the Android GATT status 133 code.
#[must_use]
pub fn is_android_gatt_133_error(error: &Error) -> bool {
    matches!(error, Error::Platform { code: 133, .. })
}

/// Software evaluation of [`ScanFilter`] against one advertisement.
///
/// Every specified field must match (AND). Used by
/// [`ConnectionSupervisor::reconnect_by_filter`]; platforms with hardware
/// filtering push the same fields down natively where available.
#[must_use]
pub fn matches_scan_filter(advertisement: &AdvertisementData, filter: &ScanFilter) -> bool {
    if let Some(prefix) = &filter.name_prefix {
        match &advertisement.local_name {
            Some(name) if name.starts_with(prefix) => {}
            _ => return false,
        }
    }
    if !filter.services.is_empty()
        && !filter
            .services
            .iter()
            .any(|service| advertisement.services.contains(service))
    {
        return false;
    }
    if let Some(manufacturer) = &filter.manufacturer_data {
        match &advertisement.manufacturer_data {
            Some((company_id, data)) => {
                if *company_id != manufacturer.company_id
                    || !data.starts_with(&manufacturer.data_prefix)
                {
                    return false;
                }
            }
            None => return false,
        }
    }
    if let Some(threshold) = filter.rssi_threshold {
        match advertisement.rssi {
            Some(rssi) if rssi >= threshold => {}
            _ => return false,
        }
    }
    true
}

/// Deterministic xorshift64* generator for backoff jitter.
///
/// No OS entropy is involved (that keeps `rblue-api` portable to
/// `wasm32-unknown-unknown` without `getrandom`), and sequences are
/// reproducible from a seed, which is exactly the property jitter needs.
#[derive(Debug, Clone)]
struct XorShift64Star {
    state: u64,
}

impl XorShift64Star {
    fn new(seed: u64) -> Self {
        Self {
            state: if seed == 0 {
                0x9E37_79B9_7F4A_7C15
            } else {
                seed
            },
        }
    }

    fn next_u64(&mut self) -> u64 {
        let mut x = self.state;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.state = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    /// Uniform in `[0, 1)`.
    fn next_unit(&mut self) -> f64 {
        ((self.next_u64() >> 11) as f64) / (1u64 << 53) as f64
    }
}

fn device_seed(id: &DeviceId) -> u64 {
    const FNV_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
    const FNV_PRIME: u64 = 0x0000_0100_0000_01b3;
    fn mix(hash: &mut u64, bytes: &[u8]) {
        for byte in bytes {
            *hash ^= u64::from(*byte);
            *hash = hash.wrapping_mul(FNV_PRIME);
        }
    }
    let mut hash = FNV_OFFSET;
    match id {
        DeviceId::Mac(bytes, kind) => {
            mix(&mut hash, bytes);
            mix(&mut hash, &[*kind as u8]);
        }
        DeviceId::Uuid(uuid) => mix(&mut hash, &uuid.as_u128().to_le_bytes()),
        DeviceId::Web(web_id) => mix(&mut hash, web_id.as_bytes()),
    }
    hash
}

/// Pure per-device supervision state machine: event/attempt outcomes in,
/// [`Disposition`] out. The async driver owns the actual timers and
/// connection calls; this type owns the invariants (counter monotonicity,
/// backoff bounds, breaker semantics) and is the unit under the property
/// tests.
#[derive(Debug)]
pub struct SupervisionState {
    policy: Arc<ReconnectPolicy>,
    rng: XorShift64Star,
    phase: SupervisionPhase,
    failures: u32,
    last_failure_133: bool,
}

impl SupervisionState {
    /// Creates the state machine for one device.
    #[must_use]
    pub fn new(id: &DeviceId, policy: Arc<ReconnectPolicy>) -> Self {
        let seed = policy.jitter_seed.unwrap_or_else(|| device_seed(id));
        Self {
            policy,
            rng: XorShift64Star::new(seed),
            phase: SupervisionPhase::Dormant,
            failures: 0,
            last_failure_133: false,
        }
    }

    /// (Re-)arms supervision: clears the breaker, gives-up state and
    /// failure counters, and makes the next loop tick start an attempt.
    /// This is what `auto_connect` does to each watched device.
    pub fn request(&mut self) {
        self.failures = 0;
        self.last_failure_133 = false;
        self.phase = SupervisionPhase::Armed;
    }

    /// Marks the start of a connection attempt. Only meaningful from the
    /// [`SupervisionPhase::Armed`] or [`SupervisionPhase::Backoff`] phases.
    pub fn begin_attempt(&mut self) {
        if matches!(
            self.phase,
            SupervisionPhase::Armed | SupervisionPhase::Backoff
        ) {
            self.phase = SupervisionPhase::Attempting;
        }
    }

    /// Records a successful connection (from a resolved `connect` call or
    /// a `DeviceConnected` event - whichever arrives first wins, the
    /// second is a no-op). Returns `true` when this was a transition.
    pub fn on_connected(&mut self) -> bool {
        if self.phase == SupervisionPhase::Connected {
            return false;
        }
        self.failures = 0;
        self.last_failure_133 = false;
        self.phase = SupervisionPhase::Connected;
        true
    }

    /// Records a link drop. Only counted while the device was believed
    /// connected or mid-attempt (duplicate disconnect events are absorbed,
    /// which is the anti-double-counting invariant).
    pub fn on_disconnected(&mut self, reason: Option<DisconnectReason>) -> Disposition {
        match self.phase {
            SupervisionPhase::Connected | SupervisionPhase::Attempting => {}
            _ => return Disposition::Ignored,
        }
        if is_android_gatt_133_reason(reason.as_ref()) {
            return self.record_failure(true);
        }
        if reason == Some(DisconnectReason::Local) && !self.policy.reconnect_on_local_disconnect {
            self.phase = SupervisionPhase::Dormant;
            return Disposition::Ignored;
        }
        self.record_failure(false)
    }

    /// Records a failed connection attempt. Counts only while an attempt
    /// is in flight; a disconnect event already accounted for the failure.
    pub fn on_attempt_failed(&mut self, error: &Error) -> Disposition {
        if self.phase != SupervisionPhase::Attempting {
            return Disposition::Ignored;
        }
        self.record_failure(is_android_gatt_133_error(error))
    }

    /// Current phase.
    #[must_use]
    pub const fn phase(&self) -> SupervisionPhase {
        self.phase
    }

    /// Consecutive failures since the last success/re-arm; the circuit
    /// breaker counter.
    #[must_use]
    pub const fn consecutive_failures(&self) -> u32 {
        self.failures
    }

    /// Whether the last recorded failure was the Android GATT status 133.
    #[must_use]
    pub const fn last_failure_was_133(&self) -> bool {
        self.last_failure_133
    }

    /// Base backoff before jitter: `initial_backoff` (or
    /// `gatt_133_backoff` after a status 133) grown by the multiplier per
    /// consecutive failure, capped at `max_backoff`.
    #[must_use]
    pub fn base_delay(&self) -> Duration {
        let initial = if self.last_failure_133 {
            self.policy.gatt_133_backoff
        } else {
            self.policy.initial_backoff
        };
        let multiplier = self.policy.multiplier.max(1.0);
        let steps = self.failures.saturating_sub(1).min(62) as f64;
        let raw = initial.as_secs_f64() * multiplier.powf(steps);
        Duration::from_secs_f64(raw.min(self.policy.max_backoff.as_secs_f64()).max(0.0))
    }

    fn record_failure(&mut self, is_133: bool) -> Disposition {
        self.failures = self.failures.saturating_add(1);
        self.last_failure_133 = is_133;
        if self
            .policy
            .breaker_threshold
            .is_some_and(|threshold| self.failures >= threshold)
        {
            self.phase = SupervisionPhase::BreakerOpen;
            return Disposition::BreakerOpen;
        }
        if self
            .policy
            .max_attempts
            .is_some_and(|max| self.failures >= max)
        {
            self.phase = SupervisionPhase::GaveUp;
            return Disposition::GaveUp;
        }
        let delay = self.jittered_base_delay();
        self.phase = SupervisionPhase::Backoff;
        Disposition::RetryAfter(delay)
    }

    fn jittered_base_delay(&mut self) -> Duration {
        let jitter = self.policy.jitter_fraction.clamp(0.0, 1.0);
        let base = self.base_delay();
        if jitter == 0.0 {
            return base;
        }
        let factor = 1.0 + jitter * (2.0 * self.rng.next_unit() - 1.0);
        Duration::from_secs_f64((base.as_secs_f64() * factor).max(0.0))
    }
}

/// Events surfaced by the supervisor loop for applications (session
/// restore, UI state).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SupervisorEvent {
    /// A watched device connected (link established or re-established).
    Connected(DeviceId),
    /// A watched device dropped and a reconnect was scheduled.
    ReconnectScheduled {
        /// Device that dropped.
        id: DeviceId,
        /// Backoff before the next attempt.
        delay: Duration,
        /// Consecutive failure count at scheduling time.
        attempt: u32,
    },
    /// A connection attempt failed.
    AttemptFailed {
        /// Device whose attempt failed.
        id: DeviceId,
        /// The failure was the Android GATT status 133.
        platform_133: bool,
        /// Consecutive failure count after this failure.
        attempt: u32,
        /// When the next attempt is scheduled; `None` when the breaker
        /// opened or the supervisor gave up.
        next_retry: Option<Duration>,
    },
    /// The circuit breaker opened for this device.
    BreakerOpen {
        /// Device whose breaker opened.
        id: DeviceId,
        /// Consecutive failures at trip time.
        consecutive_failures: u32,
    },
    /// The supervisor gave up on this device.
    GaveUp {
        /// Device given up on.
        id: DeviceId,
        /// Consecutive failures at give-up time.
        consecutive_failures: u32,
    },
}

/// Commands accepted from [`SupervisorHandle`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SupervisorCommand {
    /// Register a device and start a connection attempt now; re-arms a
    /// device whose breaker opened or that was given up on.
    Watch(DeviceId),
    /// Stop supervising a device; pending backoffs are dropped.
    Unwatch(DeviceId),
    /// Stop the supervisor loop.
    Shutdown,
}

/// Stream of [`SupervisorEvent`] values.
pub type SupervisorEventStream = mpsc::Receiver<SupervisorEvent>;

struct DeviceRuntime {
    state: SupervisionState,
    next_attempt_at: Option<Instant>,
}

/// Control-flow outcome of one loop step: keep running, stop on command, or
/// stop because the event consumer is gone.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Flow {
    Continue,
    Shutdown,
    ConsumerGone,
}

struct Inner {
    adapter: Arc<dyn Adapter>,
    policy: Arc<ReconnectPolicy>,
    devices: Mutex<HashMap<DeviceId, DeviceRuntime>>,
    events: mpsc::Sender<SupervisorEvent>,
}

impl Inner {
    fn lock(&self) -> std::sync::MutexGuard<'_, HashMap<DeviceId, DeviceRuntime>> {
        self.devices
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }

    /// Returns the delay until the nearest pending attempt, or the idle
    /// tick when none is scheduled.
    fn time_to_next_deadline(&self) -> Duration {
        let now = Instant::now();
        let next = self
            .lock()
            .values()
            .filter_map(|runtime| runtime.next_attempt_at)
            .min();
        next.map_or(IDLE_TICK, |at| at.saturating_duration_since(now))
    }

    /// Delivers one event; a failed send means the consumer is gone.
    async fn send(&self, event: SupervisorEvent) -> Flow {
        if self.events.clone().send(event).await.is_ok() {
            Flow::Continue
        } else {
            Flow::ConsumerGone
        }
    }

    /// Applies a command.
    async fn handle_command(&self, command: SupervisorCommand) -> Flow {
        match command {
            SupervisorCommand::Watch(id) => {
                {
                    let mut devices = self.lock();
                    let runtime = devices.entry(id.clone()).or_insert_with(|| DeviceRuntime {
                        state: SupervisionState::new(&id, Arc::clone(&self.policy)),
                        next_attempt_at: None,
                    });
                    runtime.state.request();
                    runtime.next_attempt_at = Some(Instant::now());
                }
                tracing::debug!("supervisor: device armed for connection");
                Flow::Continue
            }
            SupervisorCommand::Unwatch(id) => {
                self.lock().remove(&id);
                Flow::Continue
            }
            SupervisorCommand::Shutdown => Flow::Shutdown,
        }
    }

    /// Applies one adapter event to the matching device state machine.
    async fn handle_event(&self, event: AdapterEvent) -> Flow {
        match event {
            AdapterEvent::DeviceConnected(id) => {
                let changed = {
                    let mut devices = self.lock();
                    match devices.get_mut(&id) {
                        Some(runtime) => {
                            runtime.next_attempt_at = None;
                            runtime.state.on_connected()
                        }
                        None => false,
                    }
                };
                if changed {
                    self.send(SupervisorEvent::Connected(id)).await
                } else {
                    Flow::Continue
                }
            }
            AdapterEvent::DeviceDisconnected(id, reason) => {
                let disposition = match self.lock().get_mut(&id) {
                    Some(runtime) => runtime.state.on_disconnected(reason),
                    None => return Flow::Continue,
                };
                self.apply_disposition(&id, disposition, false).await
            }
            _ => Flow::Continue,
        }
    }

    /// Turns a state-machine disposition into timers and surfaced events.
    /// `from_attempt` marks dispositions produced by a finished connect
    /// call (which also emits `AttemptFailed`).
    async fn apply_disposition(
        &self,
        id: &DeviceId,
        disposition: Disposition,
        from_attempt: bool,
    ) -> Flow {
        match disposition {
            Disposition::Ignored => Flow::Continue,
            Disposition::RetryAfter(delay) => {
                // Short lock: record the timer and grab the counters, then
                // send with no lock held.
                let snapshot = {
                    let mut devices = self.lock();
                    match devices.get_mut(id) {
                        Some(runtime) => {
                            runtime.next_attempt_at = Some(Instant::now() + delay);
                            Some((
                                runtime.state.consecutive_failures(),
                                runtime.state.last_failure_was_133(),
                            ))
                        }
                        None => None,
                    }
                };
                match snapshot {
                    Some((attempt, platform_133)) => {
                        let event = if from_attempt {
                            SupervisorEvent::AttemptFailed {
                                id: id.clone(),
                                platform_133,
                                attempt,
                                next_retry: Some(delay),
                            }
                        } else {
                            SupervisorEvent::ReconnectScheduled {
                                id: id.clone(),
                                delay,
                                attempt,
                            }
                        };
                        self.send(event).await
                    }
                    None => Flow::Continue,
                }
            }
            Disposition::BreakerOpen | Disposition::GaveUp => {
                let snapshot = self.lock().get(id).map(|runtime| {
                    (
                        runtime.state.consecutive_failures(),
                        runtime.state.last_failure_was_133(),
                    )
                });
                let Some((failures, platform_133)) = snapshot else {
                    return Flow::Continue;
                };
                if from_attempt {
                    let flow = self
                        .send(SupervisorEvent::AttemptFailed {
                            id: id.clone(),
                            platform_133,
                            attempt: failures,
                            next_retry: None,
                        })
                        .await;
                    if flow != Flow::Continue {
                        return flow;
                    }
                }
                let event = match disposition {
                    Disposition::BreakerOpen => SupervisorEvent::BreakerOpen {
                        id: id.clone(),
                        consecutive_failures: failures,
                    },
                    _ => SupervisorEvent::GaveUp {
                        id: id.clone(),
                        consecutive_failures: failures,
                    },
                };
                self.send(event).await
            }
        }
    }

    /// Starts (serialized) connection attempts for every device whose
    /// backoff elapsed.
    async fn fire_due(&self) -> Flow {
        let now = Instant::now();
        let due: Vec<DeviceId> = {
            let devices = self.lock();
            devices
                .iter()
                .filter(|(_, runtime)| {
                    runtime.next_attempt_at.is_some_and(|at| at <= now)
                        && matches!(
                            runtime.state.phase(),
                            SupervisionPhase::Armed | SupervisionPhase::Backoff
                        )
                })
                .map(|(id, _)| id.clone())
                .collect()
        };
        for id in due {
            let flow = self.attempt(&id).await;
            if flow != Flow::Continue {
                return flow;
            }
        }
        Flow::Continue
    }

    /// One serialized connection attempt: re-resolve the peripheral from
    /// the adapter (the "rebuild the whole connection" step - backends drop
    /// their stale connection object here), then connect.
    async fn attempt(&self, id: &DeviceId) -> Flow {
        {
            let mut devices = self.lock();
            let Some(runtime) = devices.get_mut(id) else {
                return Flow::Continue;
            };
            if runtime
                .next_attempt_at
                .is_some_and(|at| at > Instant::now())
            {
                return Flow::Continue;
            }
            runtime.state.begin_attempt();
        }
        let result = match self.adapter.peripheral(id).await {
            Ok(peripheral) => peripheral.connect().await,
            Err(err) => Err(err),
        };
        self.finish_attempt(id, result).await
    }

    async fn finish_attempt(&self, id: &DeviceId, result: Result<(), Error>) -> Flow {
        match result {
            Ok(()) => {
                let changed = {
                    let mut devices = self.lock();
                    match devices.get_mut(id) {
                        Some(runtime) => {
                            runtime.next_attempt_at = None;
                            runtime.state.on_connected()
                        }
                        None => return Flow::Continue,
                    }
                };
                if changed {
                    self.send(SupervisorEvent::Connected(id.clone())).await
                } else {
                    Flow::Continue
                }
            }
            Err(err) => {
                tracing::debug!(error = %err, "supervisor: connection attempt failed");
                let disposition = match self.lock().get_mut(id) {
                    Some(runtime) => runtime.state.on_attempt_failed(&err),
                    None => return Flow::Continue,
                };
                self.apply_disposition(id, disposition, true).await
            }
        }
    }
}

/// The connection supervisor: one future per adapter, supervising any
/// number of watched devices. Control it through the paired
/// [`SupervisorHandle`]; consume its [`SupervisorEventStream`] to drive
/// session restore and UI state.
pub struct ConnectionSupervisor {
    inner: Arc<Inner>,
    commands: mpsc::Receiver<SupervisorCommand>,
}

/// Cloneable control handle for the supervisor; dropping all handles stops
/// the loop.
#[derive(Debug, Clone)]
pub struct SupervisorHandle {
    commands: mpsc::Sender<SupervisorCommand>,
}

impl SupervisorHandle {
    /// Registers `id` for supervision and starts a connection attempt
    /// immediately; re-arms a device whose breaker opened or that the
    /// supervisor gave up on.
    ///
    /// # Errors
    ///
    /// [`Error::InvalidState`] when the supervisor loop is gone.
    pub async fn auto_connect(&self, id: DeviceId) -> Result<(), Error> {
        self.commands
            .clone()
            .send(SupervisorCommand::Watch(id))
            .await
            .map_err(|_| Error::InvalidState("supervisor is not running".to_owned()))
    }

    /// Stops supervising `id`; pending backoffs are dropped and no further
    /// reconnection happens.
    ///
    /// # Errors
    ///
    /// [`Error::InvalidState`] when the supervisor loop is gone.
    pub async fn unwatch(&self, id: DeviceId) -> Result<(), Error> {
        self.commands
            .clone()
            .send(SupervisorCommand::Unwatch(id))
            .await
            .map_err(|_| Error::InvalidState("supervisor is not running".to_owned()))
    }

    /// Requests a clean stop of the supervisor loop. Safe to call twice.
    pub async fn shutdown(&self) {
        let _ = self
            .commands
            .clone()
            .send(SupervisorCommand::Shutdown)
            .await;
    }
}

enum LoopStep {
    Command(SupervisorCommand),
    Event(AdapterEvent),
    Timer,
}

impl ConnectionSupervisor {
    /// Creates the supervisor for `adapter` with `policy`. Returns the
    /// supervisor future owner, the control handle, and the event stream.
    ///
    /// Note the adapter is held for the supervisor's lifetime; pass a
    /// clone if the application also drives scans itself.
    #[must_use]
    pub fn new(
        adapter: Arc<dyn Adapter>,
        policy: ReconnectPolicy,
    ) -> (Self, SupervisorHandle, SupervisorEventStream) {
        // Bounded channels: a stalled event consumer backpressures the
        // supervisor loop instead of growing memory.
        let (event_tx, event_rx) = mpsc::channel(64);
        let (command_tx, command_rx) = mpsc::channel(16);
        let inner = Arc::new(Inner {
            adapter,
            policy: Arc::new(policy),
            devices: Mutex::new(HashMap::new()),
            events: event_tx,
        });
        (
            Self {
                inner,
                commands: command_rx,
            },
            SupervisorHandle {
                commands: command_tx,
            },
            event_rx,
        )
    }

    /// The policy the supervisor runs with.
    #[must_use]
    pub fn policy(&self) -> &ReconnectPolicy {
        &self.inner.policy
    }

    /// Runs the supervision loop until [`SupervisorCommand::Shutdown`],
    /// all handles are dropped, or the adapter event stream ends.
    ///
    /// The loop processes adapter events, schedules backoff timers, and
    /// performs connection attempts serialized one at a time. A stalled
    /// event consumer backpressures the loop (bounded channel).
    pub async fn run(self) -> Result<(), Error> {
        let inner = Arc::clone(&self.inner);
        let mut events = inner.adapter.events().fuse();
        let mut commands = self.commands.fuse();
        loop {
            let mut timer = futures_timer::Delay::new(inner.time_to_next_deadline()).fuse();
            let step = futures::select! {
                command = commands.next() => match command {
                    Some(command) => LoopStep::Command(command),
                    None => break,
                },
                event = events.next() => match event {
                    Some(event) => LoopStep::Event(event),
                    None => break,
                },
                _ = timer => LoopStep::Timer,
            };
            let flow = match step {
                LoopStep::Command(command) => inner.handle_command(command).await,
                LoopStep::Event(event) => inner.handle_event(event).await,
                LoopStep::Timer => inner.fire_due().await,
            };
            match flow {
                Flow::Continue => {}
                Flow::Shutdown => break,
                Flow::ConsumerGone => {
                    tracing::warn!("supervisor event consumer dropped; stopping loop");
                    break;
                }
            }
        }
        Ok(())
    }

    /// Reconnects across an RPA rotation: re-scans with `filter`, waits up
    /// to `timeout` for the first matching advertisement, then resolves
    /// the peripheral and connects. The scan is stopped on every exit
    /// path.
    ///
    /// This is the manual counterpart to watching a device: use it when a
    /// persisted `DeviceId::Mac` stopped resolving (the address rotated)
    /// and the identity lives in the advertisement fingerprint instead.
    ///
    /// # Errors
    ///
    /// [`Error::Timeout`] when no matching device appeared in time, scan
    /// and permission errors from `start_scan`, [`Error::NotFound`] when
    /// the discovered device vanished before `peripheral` resolved, and
    /// connection errors from `connect`.
    pub async fn reconnect_by_filter(
        adapter: &Arc<dyn Adapter>,
        filter: &ScanFilter,
        timeout: Duration,
    ) -> Result<Arc<dyn Peripheral>, Error> {
        adapter.start_scan(filter).await?;
        let mut events = adapter.events().fuse();
        let search: std::pin::Pin<
            Box<dyn std::future::Future<Output = Result<DiscoveredDevice, Error>>>,
        > = Box::pin(async {
            loop {
                match events.next().await {
                    Some(AdapterEvent::DeviceDiscovered(device))
                        if matches_scan_filter(&device.advertisement, filter) =>
                    {
                        break Ok(device);
                    }
                    Some(_) => continue,
                    None => {
                        break Err(Error::Backend(
                            "adapter event stream ended during reconnect scan".to_owned(),
                        ));
                    }
                }
            }
        });
        let outcome = futures::future::select(search, futures_timer::Delay::new(timeout)).await;
        let result = match outcome {
            Either::Left((found, _)) => {
                let peripheral = adapter.peripheral(&found?.id).await?;
                peripheral.connect().await?;
                Ok(peripheral)
            }
            Either::Right(((), _)) => Err(Error::Timeout),
        };
        if let Err(err) = adapter.stop_scan().await {
            // Never mask the connect/timeout outcome with a stop failure.
            tracing::debug!(error = %err, "stop_scan failed after reconnect scan");
        }
        result
    }
}

