//! Connection supervision: automatic (re)connection with exponential
//! backoff, the Android GATT status 133 special case, a failure circuit
//! breaker, and filter-based reconnection across RPA rotations.
//!
//! # Why a supervisor
//!
//! BLE links drop (supervision timeout, peer power-off, room walls) and
//! connection attempts fail transiently (congestion, Android GATT status
//! 133). Applications should not hand-roll retry loops; the supervisor
//! consumes the adapter event stream and owns one state machine per
//! watched device ([`SupervisionState`], a pure, property-testable core).
//!
//! # Backoff policy
//!
//! Exponential backoff from [`ReconnectPolicy::initial_backoff`] (500 ms),
//! multiplied by [`ReconnectPolicy::multiplier`] (2) per consecutive
//! failure, capped at [`ReconnectPolicy::max_backoff`] (30 s), with
//! +/-20% jitter ([`ReconnectPolicy::jitter_fraction`]) so fleets of
//! devices do not retry in lockstep. Jitter is generated by a deterministic
//! xorshift generator seeded per device, so backoff sequences are
//! reproducible in tests.
//!
//! # Android GATT status 133
//!
//! Status 133 is Android's generic "the GATT stack gave up" code and
//! retrying immediately almost always fails again. The supervisor treats
//! it specially whether it arrives as [`Error::Platform`] (from
//! `connect`) or as [`DisconnectReason::Platform`] (from the event
//! stream): the next backoff uses the longer
//! [`ReconnectPolicy::gatt_133_backoff`] base, and every attempt
//! re-resolves the peripheral handle from the adapter - at this layer the
//! analogue of tearing the `BluetoothGatt` object down and rebuilding the
//! whole `connectGatt` sequence (backends that can fall back to
//! `autoConnect=true` do so below the trait surface). Consecutive failures
//! feed the circuit breaker.
//!
//! # Circuit breaker
//!
//! After [`ReconnectPolicy::breaker_threshold`] consecutive failures the
//! supervisor stops retrying and emits [`SupervisorEvent::BreakerOpen`];
//! [`ReconnectPolicy::max_attempts`] gives up permanently
//! ([`SupervisorEvent::GaveUp`]). Calling `auto_connect` again re-arms a
//! device.
//!
//! # RPA rotation and `reconnect_by_filter`
//!
//! Resolvable private addresses rotate roughly every 15 minutes, so a
//! persisted [`DeviceId::Mac`] stops resolving. The recovery is re-scan
//! and match on advertisement fingerprints
//! ([`ConnectionSupervisor::reconnect_by_filter`]), not address reuse.
//!
//! # Runtime model
//!
//! The supervisor is runtime-agnostic: timers come from `futures-timer`
//! and the loop is one future ([`ConnectionSupervisor::run`]). Connection
//! attempts are serialized inside the loop (one GATT connect at a time);
//! while an attempt is in flight, adapter events queue up and are
//! processed afterwards.
//!
//! ```no_run
//! use std::sync::Arc;
//! use futures::StreamExt;
//! use rblue_api::prelude::*;
//! use rblue_api::supervisor::{ConnectionSupervisor, ReconnectPolicy, SupervisorEvent};
//!
//! # async fn demo(adapter: Arc<dyn Adapter>, device: DeviceId) -> Result<(), Error> {
//! let (supervisor, handle, mut events) =
//!     ConnectionSupervisor::new(Arc::clone(&adapter), ReconnectPolicy::default());
//! tokio::spawn(supervisor.run());
//!
//! handle.auto_connect(device).await?;
//! while let Some(event) = events.next().await {
//!     match event {
//!         SupervisorEvent::Connected(id) => {
//!             // Run the session-restore pipeline for `id` here.
//!         }
//!         SupervisorEvent::BreakerOpen { id, .. } => break,
//!         _ => {}
//!     }
//! }
//! # Ok(())
//! # }
//! ```

