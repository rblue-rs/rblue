    proptest! {
        #![proptest_config(ProptestConfig::with_cases(512))]

        #[test]
        fn state_machine_invariants_hold_under_arbitrary_sequences(
            policy in any_policy(),
            steps in prop::collection::vec(any_step(), 0..96),
        ) {
            let mut state = SupervisionState::new(&device(), Arc::new(policy.clone()));
            let mut previous_failures = 0u32;
            for step in steps {
                let disposition = match &step {
                    Step::Connected => {
                        state.on_connected();
                        Disposition::Ignored
                    }
                    Step::Disconnected(reason) => {
                        state.on_disconnected(reason.as_ref().copied())
                    }
                    Step::AttemptFailed { platform_133 } => {
                        let error = if *platform_133 {
                            error_133()
                        } else {
                            Error::Disconnected
                        };
                        state.on_attempt_failed(&error)
                    }
                    Step::BeginAttempt => {
                        state.begin_attempt();
                        Disposition::Ignored
                    }
                    Step::Request => {
                        state.request();
                        Disposition::Ignored
                    }
                };

                let failures = state.consecutive_failures();
                // Invariant: the breaker counter is monotonic between resets.
                match &step {
                    Step::Connected | Step::Request => {
                        prop_assert_eq!(failures, 0, "reset steps clear the counter");
                    }
                    _ => {
                        prop_assert!(failures >= previous_failures,
                            "counter never decreases except on reset");
                        prop_assert!(failures <= previous_failures + 1,
                            "counter grows by at most one per event");
                    }
                }
                previous_failures = failures;

                // Invariant: every scheduled delay respects the policy bounds.
                if let Disposition::RetryAfter(delay) = disposition {
                    let jitter = policy.jitter_fraction.clamp(0.0, 1.0);
                    let upper =
                        policy.max_backoff.mul_f64(1.0 + jitter) + Duration::from_millis(1);
                    let lower_base = policy.initial_backoff.min(policy.gatt_133_backoff);
                    let lower = lower_base
                        .mul_f64((1.0 - jitter).max(0.0))
                        .saturating_sub(Duration::from_millis(1));
                    prop_assert!(delay <= upper, "delay {delay:?} exceeds cap {upper:?}");
                    prop_assert!(delay >= lower, "delay {delay:?} below floor {lower:?}");
                    prop_assert_eq!(state.phase(), SupervisionPhase::Backoff);
                }

                // Invariant: breaker/give-up semantics are exact.
                if let Disposition::BreakerOpen = disposition {
                    prop_assert_eq!(
                        Some(failures),
                        policy.breaker_threshold,
                        "breaker opens exactly at the threshold"
                    );
                    prop_assert_eq!(state.phase(), SupervisionPhase::BreakerOpen);
                }
                if let Disposition::GaveUp = disposition {
                    prop_assert_eq!(Some(failures), policy.max_attempts);
                    prop_assert_eq!(state.phase(), SupervisionPhase::GaveUp);
                }
                if state.phase() == SupervisionPhase::BreakerOpen {
                    prop_assert!(matches!(
                        policy.breaker_threshold,
                        Some(threshold) if failures >= threshold
                    ));
                    prop_assert!(
                        matches!(disposition, Disposition::Ignored | Disposition::BreakerOpen),
                        "no new retry may be scheduled while the breaker is open"
                    );
                }
                if state.phase() == SupervisionPhase::GaveUp {
                    prop_assert!(matches!(
                        policy.max_attempts,
                        Some(max) if failures >= max
                    ));
                }
            }
        }
    }

