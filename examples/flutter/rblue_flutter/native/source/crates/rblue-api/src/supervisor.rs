    fn fast_policy() -> ReconnectPolicy {
        policy(0.0)
    }

    async fn next_event(events: &mut SupervisorEventStream) -> Option<SupervisorEvent> {
        let wait = futures_timer::Delay::new(Duration::from_secs(2));
        match futures::future::select(events.next(), wait).await {
            Either::Left((event, _)) => event,
            Either::Right(((), _)) => panic!("timed out waiting for supervisor event"),
        }
    }

    #[tokio::test]
    async fn auto_connect_retries_through_133_then_connects() {
        let (adapter, peripheral) = ScriptedAdapter::new(device(), 2, error_133);
        let (supervisor, handle, mut events) =
            ConnectionSupervisor::new(Arc::clone(&adapter) as Arc<dyn Adapter>, fast_policy());
        let loop_handle = tokio::spawn(supervisor.run());

        handle.auto_connect(device()).await.expect("arm");

        for expected_attempt in 1..=2u32 {
            match next_event(&mut events).await.expect("event") {
                SupervisorEvent::AttemptFailed {
                    platform_133,
                    attempt,
                    next_retry,
                    ..
                } => {
                    assert!(platform_133);
                    assert_eq!(attempt, expected_attempt);
                    assert!(next_retry.is_some());
                }
                other => panic!("expected AttemptFailed, got {other:?}"),
            }
        }
        match next_event(&mut events).await.expect("event") {
            SupervisorEvent::Connected(id) => assert_eq!(id, device()),
            other => panic!("expected Connected, got {other:?}"),
        }
        assert_eq!(peripheral.connect_calls(), 3);
        handle.shutdown().await;
        let _ = loop_handle.await;
    }

    #[tokio::test]
    async fn breaker_opens_after_consecutive_133_failures() {
        let (adapter, peripheral) = ScriptedAdapter::new(device(), u32::MAX, error_133);
        let mut policy = fast_policy();
        policy.breaker_threshold = Some(2);
        policy.gatt_133_backoff = Duration::from_millis(2);
        let (supervisor, handle, mut events) =
            ConnectionSupervisor::new(Arc::clone(&adapter) as Arc<dyn Adapter>, policy);
        let loop_handle = tokio::spawn(supervisor.run());

        handle.auto_connect(device()).await.expect("arm");

        match next_event(&mut events).await.expect("event") {
            SupervisorEvent::AttemptFailed { attempt, .. } => assert_eq!(attempt, 1),
            other => panic!("expected AttemptFailed, got {other:?}"),
        }
        match next_event(&mut events).await.expect("event") {
            SupervisorEvent::AttemptFailed {
                attempt,
                next_retry,
                ..
            } => {
                assert_eq!(attempt, 2);
                assert!(next_retry.is_none(), "breaker open means no retry");
            }
            other => panic!("expected AttemptFailed, got {other:?}"),
        }
        match next_event(&mut events).await.expect("event") {
            SupervisorEvent::BreakerOpen {
                consecutive_failures,
                ..
            } => assert_eq!(consecutive_failures, 2),
            other => panic!("expected BreakerOpen, got {other:?}"),
        }

        futures_timer::Delay::new(Duration::from_millis(40)).await;
        assert_eq!(
            peripheral.connect_calls(),
            2,
            "no further attempts while the breaker is open"
        );
        handle.shutdown().await;
        let _ = loop_handle.await;
    }

    #[tokio::test]
    async fn remote_disconnect_schedules_reconnect() {
        let (adapter, peripheral) = ScriptedAdapter::new(device(), 0, || Error::Disconnected);
        let (supervisor, handle, mut events) =
            ConnectionSupervisor::new(Arc::clone(&adapter) as Arc<dyn Adapter>, fast_policy());
        let loop_handle = tokio::spawn(supervisor.run());

        handle.auto_connect(device()).await.expect("arm");
        match next_event(&mut events).await.expect("event") {
            SupervisorEvent::Connected(id) => assert_eq!(id, device()),
            other => panic!("expected Connected, got {other:?}"),
        }

        // The link drops; the supervisor must reconnect through the same
        // state machine and surface Connected again.
        adapter.publish(AdapterEvent::DeviceDisconnected(
            device(),
            Some(DisconnectReason::Remote),
        ));
        match next_event(&mut events).await.expect("event") {
            SupervisorEvent::ReconnectScheduled { delay, attempt, .. } => {
                assert_eq!(delay, Duration::from_millis(10));
                assert_eq!(attempt, 1);
            }
            other => panic!("expected ReconnectScheduled, got {other:?}"),
        }
        match next_event(&mut events).await.expect("event") {
            SupervisorEvent::Connected(id) => assert_eq!(id, device()),
            other => panic!("expected Connected, got {other:?}"),
        }
        assert_eq!(peripheral.connect_calls(), 2);
        handle.shutdown().await;
        let _ = loop_handle.await;
    }

    #[tokio::test]
    async fn local_disconnect_does_not_reconnect() {
        let (adapter, peripheral) = ScriptedAdapter::new(device(), 0, || Error::Disconnected);
        let (supervisor, handle, mut events) =
            ConnectionSupervisor::new(Arc::clone(&adapter) as Arc<dyn Adapter>, fast_policy());
        let loop_handle = tokio::spawn(supervisor.run());

        handle.auto_connect(device()).await.expect("arm");
        match next_event(&mut events).await.expect("event") {
            SupervisorEvent::Connected(_) => {}
            other => panic!("expected Connected, got {other:?}"),
        }

        adapter.publish(AdapterEvent::DeviceDisconnected(
            device(),
            Some(DisconnectReason::Local),
        ));
        futures_timer::Delay::new(Duration::from_millis(40)).await;
        assert_eq!(
            peripheral.connect_calls(),
            1,
            "a local disconnect is deliberate; no reconnect"
        );
        // No supervisor events surfaced for the ignored disconnect.
        let quiet = futures::future::select(
            Box::pin(events.next()),
            futures_timer::Delay::new(Duration::from_millis(10)),
        )
        .await;
        assert!(matches!(quiet, Either::Right(((), _))));
        handle.shutdown().await;
        let _ = loop_handle.await;
    }

    #[tokio::test]
    async fn reconnect_by_filter_finds_and_connects() {
        let rotated = DeviceId::Mac([0x11, 0, 0, 0, 0, 2], AddressType::ResolvablePrivate);
        let (adapter, peripheral) =
            ScriptedAdapter::new(rotated.clone(), 0, || Error::Disconnected);
        let scan_adapter: Arc<dyn Adapter> = Arc::clone(&adapter) as Arc<dyn Adapter>;

        // The platform surfaces the device some time after the scan starts
        // (subscriptions opened by reconnect_by_filter must still see it).
        let advertiser = Arc::clone(&adapter);
        tokio::spawn(async move {
            futures_timer::Delay::new(Duration::from_millis(20)).await;
            advertiser.publish(AdapterEvent::DeviceDiscovered(DiscoveredDevice {
                id: rotated,
                advertisement: AdvertisementData {
                    local_name: Some("sensor-7".to_owned()),
                    ..AdvertisementData::default()
                },
            }));
        });

        let filter = ScanFilter {
            name_prefix: Some("sensor".to_owned()),
            ..ScanFilter::default()
        };
        let found = ConnectionSupervisor::reconnect_by_filter(
            &scan_adapter,
            &filter,
            Duration::from_secs(1),
        )
        .await
        .expect("reconnect by filter");
        assert_eq!(found.id(), peripheral.id());
        assert_eq!(peripheral.connect_calls(), 1);
    }

