        async fn is_connected(&self) -> Result<bool, Error> {
            Ok(false)
        }

        async fn connect(&self) -> Result<(), Error> {
            self.connect_calls
                .fetch_add(1, std::sync::atomic::Ordering::SeqCst);
            // Consume one budgeted failure without underflowing to u32::MAX.
            let mut remaining = self
                .remaining_failures
                .load(std::sync::atomic::Ordering::SeqCst);
            loop {
                if remaining == 0 {
                    break;
                }
                match self.remaining_failures.compare_exchange_weak(
                    remaining,
                    remaining - 1,
                    std::sync::atomic::Ordering::SeqCst,
                    std::sync::atomic::Ordering::SeqCst,
                ) {
                    Ok(_) => return Err((self.failure_factory)()),
                    Err(actual) => remaining = actual,
                }
            }
            self.hub
                .publish(AdapterEvent::DeviceConnected(self.id.clone()));
            Ok(())
        }

