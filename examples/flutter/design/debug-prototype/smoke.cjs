// Run with PLAYWRIGHT_MODULE pointing to an installed playwright package if needed.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.join(__dirname, 'index.html')).href);
  assert.equal(await page.locator('.device').count(), 4);
  await page.locator('#search').fill('missing');
  assert.equal(await page.locator('.device').count(), 0);
  await page.locator('#search').fill('');
  await page.locator('#scanToggle').click();
  assert.equal(await page.locator('#scanBadge').textContent(), '扫描中');
  await page.locator('#scanToggle').click();
  await page.locator('#oversize').click();
  await page.locator('#write').click();
  assert.match(await page.locator('#opResult').textContent(), /InvalidLength/);
  await page.locator('#payload').fill('ZZ');
  await page.locator('#write').click();
  assert.match(await page.locator('#opResult').textContent(), /HEX 格式无效/);
  await page.locator('#encoding').selectOption('utf8');
  await page.locator('#payload').fill('你好');
  assert.equal(await page.locator('#byteCount').textContent(), '6 bytes');
  await page.locator('#write').click();
  assert.match(await page.locator('#opResult').textContent(), /写入成功/);
  await page.locator('[data-char="1"]').click();
  assert.equal(await page.locator('#write').isDisabled(), true);
  await page.locator('#subscribe').click();
  await page.locator('[data-page="stream"]').click();
  await page.waitForFunction(() => document.querySelector('#packetRows .packet'));
  await page.locator('#pauseStream').click();
  const rowCount = await page.locator('#packetRows tr').count();
  const previousCount = await page.locator('#rxStat').textContent();
  await page.waitForFunction(previous => document.querySelector('#rxStat').textContent !== previous, previousCount);
  assert.equal(await page.locator('#packetRows tr').count(), rowCount);
  await page.locator('#pauseStream').click();
  await page.locator('[data-page="reconnect"]').click();
  await page.locator('#fault').selectOption('133');
  await page.locator('#runReconnect').click();
  await page.waitForFunction(() => document.querySelector('#retryBadge').textContent === '恢复完成');
  assert.match(await page.locator('#reconnectResult').textContent(), /原通知订阅已恢复/);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export').click();
  const download = await downloadPromise;
  const fs = require('node:fs');
  const data = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
  assert.equal(data.mode, 'prototype_mock');
  assert.ok(data.logs.some(event => event.event === 'subscription.restored'));
  await page.locator('#platform').selectOption('ios');
  assert.match(await page.locator('#connectionStat').textContent(), /未连接/);
  assert.equal(await page.locator('#fault option[value="133"]').isDisabled(), true);
  await page.locator('[data-page="devices"]').click();
  await page.locator('#connectToggle').click();
  await page.locator('#platform').selectOption('android');
  await page.locator('#connectToggle').click();
  await page.locator('[data-char="0"]').click();
  await page.locator('#encoding').selectOption('hex');
  await page.locator('#payload').fill('48 65 6C 6C 6F');
  await page.locator('[data-device="3"]').click();
  assert.equal(await page.locator('#connectToggle').isDisabled(), true);
  await page.locator('[data-device="0"]').click();
  await page.locator('[data-char="2"]').click();
  assert.equal(await page.locator('#writeMode').inputValue(), 'noresponse');
  await page.locator('#write').click();
  assert.match(await page.locator('#opResult').textContent(), /写入成功/);
  const ids = await page.locator('[id]').evaluateAll(elements => elements.map(element => element.id));
  assert.equal(new Set(ids).size, ids.length, 'IDs must be unique');
  for (const width of [1440, 1024, 844, 768, 430, 390, 375, 320]) {
    await page.setViewportSize({ width, height: 1080 });
    for (const name of ['devices', 'stream', 'reconnect', 'capabilities', 'logs']) {
      await page.locator(`[data-page="${name}"]`).click();
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Overflow at ${width}px on ${name}`);
    }
  }
  await page.reload();
  await page.mouse.move(0, 0);
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.screenshot({ path: path.join(__dirname, 'preview-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.screenshot({ path: path.join(__dirname, 'preview-mobile.png'), fullPage: true });
  assert.equal(await page.locator('.inspector-title').isVisible(), false);
  const navBounds = await page.locator('.sidebar').boundingBox();
  assert.ok(navBounds.y + navBounds.height <= 813, 'Bottom navigation must stay in viewport');
  for (const button of await page.locator('.navitem[data-page]').all()) {
    const box = await button.boundingBox();
    assert.ok(box.width >= 44 && box.height >= 44, 'Mobile navigation touch targets');
  }
  await page.locator('[data-device="0"]').click();
  assert.equal(await page.locator('.inspector-title').isVisible(), true);
  assert.equal(await page.locator('#search').isVisible(), false);
  await page.locator('[data-char="0"]').click();
  await page.locator('#encoding').selectOption('utf8');
  await page.locator('#payload').fill('手机调试');
  assert.equal(await page.locator('#byteCount').textContent(), '12 bytes');
  await page.locator('#write').click();
  assert.match(await page.locator('#opResult').textContent(), /写入成功/);
  await page.locator('#read').click();
  await page.locator('#backDevices').click();
  assert.equal(await page.locator('#search').isVisible(), true);
  await page.locator('[data-device="0"]').click();
  await page.evaluate(() => { document.activeElement.blur(); window.scrollTo(0, 0); });
  await page.mouse.move(0, 0);
  await page.screenshot({ path: path.join(__dirname, 'preview-mobile-detail.png'), fullPage: true });
  await page.locator('[data-char="1"]').click();
  await page.locator('#subscribe').click();
  await page.locator('#openStream').click();
  await page.waitForFunction(() => document.querySelector('#packetRows .packet'));
  assert.equal(await page.locator('.packet-device').first().isVisible(), true);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.evaluate(() => { document.activeElement.blur(); window.scrollTo(0, 0); });
  await page.evaluate(() => document.getElementById('toast').hidden = true);
  await page.mouse.move(0, 0);
  await page.screenshot({ path: path.join(__dirname, 'preview-mobile-stream.png'), fullPage: true });
  await page.locator('[data-page="devices"]').click();
  assert.equal(await page.locator('#search').isVisible(), true);
  await page.goto(pathToFileURL(path.join(__dirname, 'mobile.html')).href);
  await page.setViewportSize({ width: 1440, height: 1040 });
  const frame = page.frameLocator('#phone');
  await frame.locator('[data-device="0"]').click();
  assert.equal(await frame.locator('#backDevices').isVisible(), true);
  await frame.locator('#backDevices').click();
  for (const width of ['375', '390', '430']) {
    await page.locator(`[data-width="${width}"]`).click();
    assert.equal(Math.round((await page.locator('#phone').boundingBox()).width), Number(width));
  }
  await page.locator('[data-width="390"]').click();
  await page.mouse.move(0, 0);
  await page.screenshot({ path: path.join(__dirname, 'preview-mobile-board.png'), fullPage: true });
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: scan, filters, write validation, UTF-8, notify/pause, reconnect, export, platform gates mobile drill-in/back, touch targets, preview widths and responsive layouts.');
})().catch(error => { console.error(error); process.exit(1); });
